import type { StackReport } from "./types.js";

/** Short human summary of a stack report, for the terminal. */
export function formatStackSummary(report: StackReport): string {
  const lines: string[] = [];
  const known = report.units.filter((u) => u.role !== "unknown" || u.framework);
  lines.push(`Stack: ${known.length} app${known.length === 1 ? "" : "s"} found${report.units.length > known.length ? ` (+${report.units.length - known.length} other package${report.units.length - known.length === 1 ? "" : "s"})` : ""}`);
  for (const u of known) {
    const parts = [u.language, u.framework && (u.bundler && u.bundler !== "next" ? `${u.framework} (${u.bundler})` : u.framework), u.httpClient, u.schema, u.packageManager].filter(Boolean);
    const stores = u.dataStores.map((d) => d.name);
    lines.push(`  ${u.role.padEnd(9)} ${(u.dir + "/").padEnd(14)} ${parts.join(" · ")}${stores.length ? ` · stores: ${stores.join(", ")}` : ""}`);
  }
  const styles = report.apiStyles.map((s) => s.name);
  if (report.units.some((u) => u.role === "backend" || u.role === "fullstack")) styles.unshift("rest");
  const openapi = report.openapi.files.length ? `files ${report.openapi.files.join(", ")}` : report.openapi.generatedBy.length ? `generated by ${report.openapi.generatedBy.join(", ")}` : "none";
  lines.push(`API: ${[...new Set(styles)].join(", ") || "unknown"} · OpenAPI: ${openapi}`);
  if (report.joins.length) {
    lines.push("Joins:");
    for (const j of report.joins) {
      const what = j.kind === "env" ? `${j.name}${j.value ? ` = ${j.value}` : ""}` : `${j.from} -> ${j.to}`;
      lines.push(`  ${j.kind.padEnd(14)} ${what}  (${j.file}${j.line ? `:${j.line}` : ""})`);
    }
  }
  const hosts = [...new Set(report.outbound.map((o) => o.host))];
  if (hosts.length) lines.push(`Outbound hosts: ${hosts.join(", ")}`);
  if (report.lowConfidence.length) {
    lines.push("Low confidence:");
    for (const l of report.lowConfidence) lines.push(`  ${l.unit}: ${l.what} ${l.name} (${Math.round(l.confidence * 100)}%)`);
  }
  if (report.unsupported.length) {
    lines.push("Unsupported:");
    for (const u of report.unsupported) lines.push(`  ${u.dir}: ${u.reason}`);
  }
  return lines.join("\n") + "\n";
}
